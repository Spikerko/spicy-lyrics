"""Generate src/components/Utils/BrandedHeaderAssets.ts from the brand PNGs.

Spicetify extensions bundle to a single JS file with no asset-serving step, so
local artwork is alpha-trimmed, downscaled and inlined as data URIs.

Usage:  python tools/branded-header/gen_assets.py
Kept in-repo (not %TEMP%) so it survives OS temp cleanup.
"""

import base64
import io
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC_DIR = os.path.join(HERE, "source")
OUT_TS = os.path.join(REPO, "src", "components", "Utils", "BrandedHeaderAssets.ts")
TARGET_H = 200

SOURCES = [
    ("GIK_UGM", "gik-logo.png", "GIK UGM"),
    ("PJS", "pjs-logo.png", "Perayaan Jumat Sporty GIK UGM"),
]


def encode(path):
    im = Image.open(path).convert("RGBA")
    bbox = im.getchannel("A").getbbox()
    if bbox:
        im = im.crop(bbox)
    cw, ch = im.size
    w = max(1, round(TARGET_H * cw / ch))
    im = im.resize((w, TARGET_H), Image.LANCZOS)

    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    best = buf.getvalue()
    try:
        buf = io.BytesIO()
        im.quantize(colors=255, method=Image.FASTOCTREE).save(buf, "PNG", optimize=True)
        if len(buf.getvalue()) < len(best):
            best = buf.getvalue()
    except Exception:  # noqa: BLE001
        pass
    return "data:image/png;base64," + base64.b64encode(best).decode("ascii"), w, len(best)


def main():
    lines = [
        "/**",
        " * GENERATED by tools/branded-header/gen_assets.py — do not edit by hand.",
        " *",
        " * Brand logos inlined as data URIs: a Spicetify extension is one JS file with",
        " * no asset server. Each source is alpha-trimmed and scaled to 200px tall.",
        " */",
        "",
    ]
    for const, fname, label in SOURCES:
        path = os.path.join(SRC_DIR, fname)
        if not os.path.exists(path):
            sys.exit(f"missing source: {path}")
        uri, w, n = encode(path)
        lines += [
            f"/** {label}: {w}x{TARGET_H}, {n:,} bytes. */",
            f"export const {const}_LOGO =",
            f'  "{uri}";',
            f"export const {const}_ASPECT = {w} / {TARGET_H};",
            "",
        ]
        print(f"{const:8} {w}x{TARGET_H} aspect={w / TARGET_H:.3f} {n:,}b")
    with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT_TS)


if __name__ == "__main__":
    main()
