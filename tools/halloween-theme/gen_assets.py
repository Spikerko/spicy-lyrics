"""Generate src/components/Utils/HalloweenAssets.ts from the PJS #13 asset library.

Each image is alpha-trimmed, scaled to the largest size it is ever displayed at
(measured on a 2560x1440 window, with headroom), and encoded as whichever of
WebP or palette PNG is smaller. The result is inlined as data URIs, because a
Spicetify extension is a single JS file with no asset server.

Usage:  python tools/halloween-theme/gen_assets.py
"""

import base64
import io
import os
import shutil
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
LIB = r"D:\GIK-INTERN\PJS_13_Asset\pjs13\pustaka"
SRC = os.path.join(HERE, "source")  # in-repo copy, survives temp cleanup
OUT_TS = os.path.join(REPO, "src", "components", "Utils", "HalloweenAssets.ts")
BUDGET = 700 * 1024  # bytes of image data across all assets

# (export name, library path, max rendered height in px, tile mode)
# tile mode "mirror" emits [image | mirrored image] so the tile's two edges are
# the same pixel column and repeat-x has no seam. "mirror-base" also trims the
# ends to where the solid ground strip at the bottom is continuous first.
ASSETS = [
    ("MOON", "adegan/bulan.png", 420, None),
    ("CLOUDS", "adegan/awan-ungu-berlapis.png", 640, "mirror"),
    ("HOUSE", "adegan/rumah-hantu.png", 720, None),
    ("GRAVES", "adegan/kuburan.png", 150, None),
    ("TREE", "adegan/pohon-rindang.png", 960, None),
    ("GRASS", "adegan/rumput-semak-berbunga.png", 96, "mirror-base"),
    ("WEB", "hiasan/jaring-hitam.png", 300, None),
    ("BRANCH", "hiasan/cabang-labu.png", 190, None),
    ("LOGO", "logo/logo-spooky.png", 200, None),
    ("BAT_1", "hiasan/kelelawar-oranye-1.png", 80, None),
    ("BAT_2", "hiasan/kelelawar-oranye-2.png", 80, None),
    ("BAT_3", "hiasan/kelelawar-oranye-3.png", 80, None),
    ("BAT_4", "hiasan/kelelawar-oranye-4.png", 80, None),
    ("WITCH", "tokoh/penyihir.png", 320, None),
    ("LUTE", "tokoh/tupai-pemain-kecapi.png", 320, None),
    ("ZOMBIE", "tokoh/zombie.png", 300, None),
    ("NOTE_ORANGE", "hiasan/not-musik-oranye.png", 110, None),
    ("NOTE_BROWN", "hiasan/not-musik-coklat.png", 110, None),
]


def base_span(im):
    """Columns where the bottom band is mostly opaque, i.e. the ground strip."""
    a = im.getchannel("A")
    w, h = im.size
    band = a.crop((0, int(h * 0.82), w, h))
    bw, bh = band.size
    px = band.load()
    solid = [x for x in range(bw) if sum(px[x, y] > 128 for y in range(bh)) >= bh * 0.6]
    if not solid:
        return 0, w - 1
    return solid[0], solid[-1]


def mirror_tile(im, crop_base):
    if crop_base:
        x0, x1 = base_span(im)
        print(f"   ground strip continuous over columns {x0}-{x1} of {im.width}")
        im = im.crop((x0, 0, x1 + 1, im.height))
    pair = Image.new("RGBA", (im.width * 2, im.height))
    pair.paste(im, (0, 0))
    pair.paste(im.transpose(Image.FLIP_LEFT_RIGHT), (im.width, 0))
    return pair


def encode(im):
    """Return (mime, bytes) for the smaller of WebP and palette PNG."""
    candidates = []
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=84, method=6)
    candidates.append(("image/webp", buf.getvalue()))
    try:
        buf = io.BytesIO()
        im.quantize(colors=255, method=Image.FASTOCTREE).save(buf, "PNG", optimize=True)
        candidates.append(("image/png", buf.getvalue()))
    except Exception:  # noqa: BLE001
        pass
    return min(candidates, key=lambda c: len(c[1]))


def main():
    os.makedirs(SRC, exist_ok=True)
    lines = [
        "/**",
        " * GENERATED by tools/halloween-theme/gen_assets.py — do not edit by hand.",
        " *",
        " * PJS #13 Spooky artwork for the Halloween fullscreen theme, inlined as data",
        " * URIs. Each entry is alpha-trimmed and sized to its largest display size.",
        " * `ASPECT` is width / height, used to size slots without layout shift.",
        " */",
        "",
    ]
    total = 0
    for name, rel, target_h, tile in ASSETS:
        src = os.path.join(LIB, rel)
        local = os.path.join(SRC, rel.replace("/", "__"))
        # source/ holds an in-repo copy of every asset, so the generator runs
        # on any machine; LIB (the original asset library) is only needed to
        # add a new image that has no copy yet.
        if not os.path.exists(local):
            if not os.path.exists(src):
                sys.exit(f"missing asset: {local} (and no original at {src})")
            shutil.copy2(src, local)

        im = Image.open(local).convert("RGBA")
        bbox = im.getchannel("A").getbbox()
        if bbox:
            im = im.crop(bbox)
        h = min(target_h, im.height)  # never upscale
        w = max(1, round(im.width * h / im.height))
        im = im.resize((w, h), Image.LANCZOS)
        if tile:
            im = mirror_tile(im, crop_base=tile == "mirror-base")
            w, h = im.size
            # Seamless iff the tile's first and last columns are identical.
            if list(im.crop((0, 0, 1, h)).getdata()) != list(im.crop((w - 1, 0, w, h)).getdata()):
                sys.exit(f"{name}: tile edges differ, would show a seam")

        mime, data = encode(im)
        total += len(data)
        uri = f"data:{mime};base64," + base64.b64encode(data).decode("ascii")
        lines += [
            f"/** {rel}: {w}x{h} {mime.split('/')[1]}, {len(data):,} bytes. */",
            f'export const {name} = "{uri}";',
            f"export const {name}_ASPECT = {w / h:.4f};",
            "",
        ]
        print(f"{name:12} {w:>4}x{h:<4} {mime.split('/')[1]:5} {len(data):>8,} b")

    with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))

    print(f"\ntotal image data {total:,} b ({total / 1024:.0f} KB), budget {BUDGET // 1024} KB")
    print("wrote", OUT_TS)
    if total > BUDGET:
        sys.exit("over budget")


if __name__ == "__main__":
    main()
